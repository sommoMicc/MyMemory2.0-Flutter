String? deckAsset(String theme, int value) {
  final assets = deckAssets[theme];
  return assets != null && value >= 0 && value < assets.length ? assets[value] : null;
}

String? deckCover(String theme) => deckAsset(theme, 0);

String? deckLabel(String theme, int value) {
  final labels = deckLabels[theme];
  return labels != null && value >= 0 && value < labels.length ? labels[value] : null;
}

bool _licensesRegistered = false;
Future<void> registerDeckLicenses() async {
  if (_licensesRegistered) return;
  final notice = await rootBundle.loadString('assets/decks/NOTICE.txt');
  final upstream = await rootBundle.loadString('assets/decks/UPSTREAM-NOTICE.txt');
  final license = await rootBundle.loadString('assets/decks/LICENSE-APACHE-2.0.txt');
  LicenseRegistry.addLicense(() => Stream.value(
    LicenseEntryWithLineBreaks(const ['Noto Emoji 2D — deck illustrations'], '$notice\n$upstream\n$license'),
  ));
  final originalNotice = await rootBundle.loadString('assets/decks/ORIGINAL-ART-NOTICE.txt');
  LicenseRegistry.addLicense(() => Stream.value(
    LicenseEntryWithLineBreaks(const ['SommoMemory original artwork disclosure'], originalNotice),
  ));
  _licensesRegistered = true;
}
